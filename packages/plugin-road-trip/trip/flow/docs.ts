import { describeRoutes } from "./dispatch"
import { FLOW_EVENT_DOCS, type TripFlowEventType } from "./events"
import { moves, toMermaid, type MachineDef, type MachineEvent } from "./machine"
import { TRIP_MACHINES } from "./machines"
import "./index"

/**
 * `docs/road-trip-flow.md`, rendered from the machine tables and the event
 * vocabulary (ADR 0222). `npm run flow:docs` writes it; a test fails when the
 * file is stale.
 */

function machineSection(def: MachineDef<string, MachineEvent>): string {
  const lines = [
    `## ${def.id[0]!.toUpperCase()}${def.id.slice(1)}`,
    "",
    "```mermaid",
    toMermaid(def),
    "```",
    "",
  ]
  lines.push("| State | Meaning |", "|---|---|")
  for (const [state, node] of Object.entries(def.states) as [
    string,
    { description?: string; final?: true },
  ][]) {
    lines.push(`| \`${state}\`${node.final ? " (final)" : ""} | ${node.description ?? ""} |`)
  }
  lines.push("", "| Move | When |", "|---|---|")
  for (const [from, type, to] of moves(def)) {
    const why = (def.events as Record<string, string> | undefined)?.[type] ?? ""
    lines.push(`| \`${from}\` → \`${to}\` on \`${type}\` | ${why} |`)
  }
  return lines.join("\n")
}

export function renderFlowDocs(): string {
  const routes = describeRoutes()
  const events = (Object.keys(FLOW_EVENT_DOCS) as TripFlowEventType[]).map(
    (type) => `| \`${type}\` | ${routes[type] ?? "—"} | ${FLOW_EVENT_DOCS[type]} |`,
  )
  return [
    "<!-- Generated by `npm run flow:docs` in packages/plugin-road-trip. Do not edit by hand. -->",
    "",
    "# Road trip flow",
    "",
    "A trip is one statechart built from small flat machines ([ADR 0222](adrs/0222-trip-flow-and-branches.md)):",
    "the trip lifecycle runs beside one machine per site, junction (fork), layer, vote, and key item",
    "([ADR 0230](adrs/0230-trip-conditions-and-key-items.md)). Every",
    "threshold, poll close, item use, outcome, and host action becomes a flow event; `dispatch`",
    "routes it to the entity below, which runs `interpret` (conditions) → the table (legal moves)",
    "→ `onEnter` (effects).",
    "",
    "Ownership rules (enforced by `trip/flow/architecture.test.ts`):",
    "",
    "1. Only `dispatch` changes a machine: nothing outside `trip/flow/entities/` writes a phase or the trip status.",
    "2. Only `trip/flow/outcomes.ts` interprets outcomes (`unlock`, `lock`, `divert`, `give-key`, `take-key`, `give-item`),",
    "   and it checks each outcome's `when` against the trip as the list started.",
    "3. Only `road-trip-map/src/paths.ts` reads authored miles: runtime code reads the path map",
    "   (`ctx.map`, `pathFor(...)`), where sites and events sit at odometer miles.",
    "4. Only the van entity (`trip/flow/entities/van.ts`) writes the van's key items (`state.keyItems`).",
    "",
    "## Flow events",
    "",
    "| Event | Handled by | Meaning |",
    "|---|---|---|",
    ...events,
    "",
    ...TRIP_MACHINES.map(
      (def) => machineSection(def as unknown as MachineDef<string, MachineEvent>) + "\n",
    ),
  ].join("\n")
}
